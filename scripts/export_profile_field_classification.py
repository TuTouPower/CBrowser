"""Export the backend profile field classification for the frontend.

The backend splits profile fields into three classes
(`src/backend/cbrowser/adapters/database/repository.py`):
metadata fields are written directly, instant fields are applied without
a new config version, and the remaining runtime fields create a new
config version on change. The frontend submits incremental PATCHes and
must use exactly this split, so the classification is generated from
the backend constants instead of being hand-copied into TypeScript.

Usage (from the repository root):

    PYTHONPATH=src/backend python3 scripts/export_profile_field_classification.py

The checked-in output is guarded by
`tests/unit/test_t058_profile_field_classification.py`, which fails on
any drift between this export and the live backend constants.
"""

from __future__ import annotations

from pathlib import Path

from cbrowser.adapters.database.repository import (
    CONFIG_VERSION_FIELDS,
    INSTANT_FIELDS,
    METADATA_FIELDS,
)

HEADER = """/**
 * Profile field classification, generated from the backend.
 *
 * Source of truth: `src/backend/cbrowser/adapters/database/repository.py`
 * (`METADATA_FIELDS` / `INSTANT_FIELDS` / `CONFIG_VERSION_FIELDS`).
 * Generated by `scripts/export_profile_field_classification.py`; do not edit.
 */
"""


def _as_ts_array(fields) -> str:
    items = ", ".join(f'"{field}"' for field in sorted(fields))
    return f"[{items}]"


def render_profile_field_classification() -> str:
    """Render the generated TypeScript module from the live constants."""
    lines = [
        HEADER.rstrip("\n"),
        "",
        f"export const PROFILE_METADATA_FIELDS = {_as_ts_array(METADATA_FIELDS)} as const;",
        "",
        f"export const PROFILE_INSTANT_FIELDS = {_as_ts_array(INSTANT_FIELDS)} as const;",
        "",
        f"export const PROFILE_RUNTIME_FIELDS = {_as_ts_array(CONFIG_VERSION_FIELDS)} as const;",
        "",
    ]
    return "\n".join(lines)


def export_profile_field_classification(
    output_path: Path | str | None = None,
) -> Path:
    if output_path is None:
        root_dir = Path(__file__).resolve().parent.parent
        dest = (
            root_dir
            / "src"
            / "frontend"
            / "src"
            / "shared"
            / "api"
            / "generated"
            / "profile_field_classification.ts"
        )
    else:
        dest = Path(output_path).resolve()
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(render_profile_field_classification(), encoding="utf-8")
    return dest


if __name__ == "__main__":
    out = export_profile_field_classification()
    print(f"Profile field classification exported to {out}")
