"""t035 baseline-schema migration tests (AC-001/AC-002).

t035 collapsed the 0001-0009 chain into a single baseline revision.  The
old "upgrade from 0008 preserves profiles" test (which depended on the
retired 0008 -> 0009 incremental migration) and its _upgrade_to helper
were deleted wholesale, not rewritten to the new output.  Coverage added
for the new semantics: a single baseline revision with a fresh identity,
and an empty DB upgraded to head matching the ORM models (autogenerate).
The backup/restore test is kept verbatim (no retired revision id in it).
"""

from __future__ import annotations

import shutil
import sqlite3
from pathlib import Path

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from cbrowser.adapters.database.migrations import (
    BASELINE_REVISION,
    get_alembic_config,
    run_database_migrations,
)
from cbrowser.adapters.database.session import create_engine_and_maker
from cbrowser.domain.models import ProfileConfig
from cbrowser.adapters.database.repository import ProfileRepository
from cbrowser.services.control_service import ProfileControlService


async def _seed(db_path):
    run_database_migrations(db_path)
    engine, maker = create_engine_and_maker(db_path)
    repo = ProfileRepository(maker)
    profile = await repo.create_profile(
        ProfileConfig(name="Migrate", fingerprint_seed=1)
    )
    svc = ProfileControlService(maker)
    await svc.claim(profile.id, "tok-1", "exec-1")
    await svc.handoff(profile.id, "human_input")
    await engine.dispose()
    return profile.id


def _read_control(db_path):
    conn = sqlite3.connect(db_path)
    try:
        row = conn.execute(
            "SELECT owner, generation, handoff_reason,"
            " agent_reclaim_allowed FROM profile_controls"
        ).fetchone()
        return row
    finally:
        conn.close()


@pytest.mark.asyncio
async def test_migration_upgrade_backup_restore(tmp_path):
    db = tmp_path / "migrate.db"
    pid = await _seed(db)
    assert pid
    # Row persisted through the real Alembic upgrade path.
    assert _read_control(db) == ("user", 2, "human_input", 0)
    # Backup: plain file copy of the SQLite database.
    backup = tmp_path / "backup.db"
    shutil.copyfile(db, backup)
    # Restore: copy back over a fresh path and verify the state reads.
    restored = tmp_path / "restored.db"
    shutil.copyfile(backup, restored)
    assert _read_control(restored) == ("user", 2, "human_input", 0)
    # The restored database still upgrades/migrates cleanly (idempotent).
    run_database_migrations(restored)
    assert _read_control(restored) == ("user", 2, "human_input", 0)




def test_upgrade_head_matches_orm_metadata(tmp_path: Path) -> None:
    """AC-001: an empty database upgraded with `alembic upgrade head`
    yields a schema identical to the ORM models (autogenerate reports no
    diff).  Guards models.py against drift from the baseline migration;
    command.check raises AutogenerateDiffsDetected on any difference."""
    db = tmp_path / "schema.db"
    run_database_migrations(db)
    command.check(get_alembic_config(db))


def test_revision_chain_matches_shipped_migration_files(tmp_path: Path) -> None:
    """The shipped chain is the t035 baseline plus every incremental
    migration present in versions/: the head advances while the baseline
    remains the root, and each shipped file is reachable in the chain."""
    cfg = get_alembic_config(tmp_path / "chain.db")
    script = ScriptDirectory.from_config(cfg)
    chain = [rev.revision for rev in script.walk_revisions()]
    versions_dir = (
        Path(__file__).resolve().parents[2]
        / "src" / "backend" / "migrations" / "versions"
    )
    revision_files = [
        p for p in versions_dir.glob("*.py") if not p.name.startswith("__")
    ]
    assert len(chain) == len(revision_files)
    assert len(set(chain)) == len(chain)
    assert chain[-1] == BASELINE_REVISION
    baseline = script.get_revision(BASELINE_REVISION)
    assert baseline is not None
    assert baseline.down_revision is None
    heads = script.get_heads()
    assert len(heads) == 1
    assert heads[0] == chain[0]
    assert heads[0] != BASELINE_REVISION
    retired_revisions = (
        "0001_initial_schema",
        "0002_auth",
        "0006_snapshot_modes",
        "0008_artifact_delete_intent",
        "0009_profile_control_state",
    )
    assert BASELINE_REVISION not in retired_revisions
    assert all(legacy not in chain for legacy in retired_revisions)
